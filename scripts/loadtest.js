// Starts the API as a separate process, drives the board endpoint with autocannon and writes LOAD_TEST.md.
// Two passes: the default configuration (judged against the target) and the board cache switched off,
// so the report also shows what every request costs when it really runs the MongoDB query.
// The only other setting changed is RATE_LIMIT_MAX (a load test from one IP would otherwise measure the limiter).
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import os from 'node:os';
import { setTimeout as sleep } from 'node:timers/promises';
import autocannon from 'autocannon';
import { MongoClient } from 'mongodb';
import { z } from 'zod';
import { loadConfig, loadEnvFile } from '../src/config.js';

loadEnvFile();
const config = loadConfig();
const lt = z
  .object({
    LOADTEST_CONNECTIONS: z.coerce.number().int().min(1),
    LOADTEST_DURATION_SECONDS: z.coerce.number().int().min(1),
    LOADTEST_PORT: z.coerce.number().int().min(1).max(65535),
    LOADTEST_P95_TARGET_MS: z.coerce.number().min(1),
  })
  .parse(process.env);
const base = `http://127.0.0.1:${lt.LOADTEST_PORT}`;

async function pass(overrides) {
  const server = spawn(process.execPath, ['src/server.js'], {
    env: { ...process.env, PORT: String(lt.LOADTEST_PORT), RATE_LIMIT_MAX: '1000000000', LOG_LEVEL: 'silent', NODE_ENV: 'production', ...overrides },
    stdio: ['ignore', 'inherit', 'inherit'],
  });
  try {
    for (let i = 0; ; i++) {
      if (await fetch(`${base}/api/health`).then((r) => r.ok, () => false)) break;
      if (i > 100 || server.exitCode !== null) throw new Error('server did not start');
      await sleep(100);
    }
    const { hackathon } = await (await fetch(`${base}/api/meta`)).json();
    const board = `/api/hackathons/${hackathon.id}/teams`;
    // A realistic mix: first page, a page 20 cursors deep, and a skill-filtered page.
    let cursor;
    for (let i = 0; i < 20; i++) {
      const page = await (await fetch(`${base}${board}${cursor ? `?cursor=${cursor}` : ''}`)).json();
      if (!page.nextCursor) break;
      cursor = page.nextCursor;
    }
    const paths = [board, cursor ? `${board}?cursor=${cursor}` : board, `${board}?skill=design`];

    const samples = [];
    const instance = autocannon({
      url: base,
      connections: lt.LOADTEST_CONNECTIONS,
      duration: lt.LOADTEST_DURATION_SECONDS,
      requests: paths.map((path) => ({ method: 'GET', path })),
    });
    instance.on('response', (_client, _status, _bytes, responseTime) => samples.push(responseTime));
    const result = await instance;

    // Exact percentiles from every response time (autocannon's own summary has no p95).
    samples.sort((a, b) => a - b);
    const pct = (p) => samples[Math.min(samples.length - 1, Math.ceil((p / 100) * samples.length) - 1)];
    return {
      board,
      p50: pct(50),
      p95: pct(95),
      p99: pct(99),
      max: samples.at(-1),
      rps: result.requests.average,
      total: result.requests.total,
      ok: result['2xx'],
      failed: result.errors + result.timeouts + result.non2xx,
    };
  } finally {
    server.kill();
    await new Promise((resolve) => server.once('exit', resolve));
  }
}

const cached = await pass({});
const uncached = await pass({ BOARD_CACHE_TTL_MS: '0' });

const client = new MongoClient(config.MONGODB_URI);
const db = client.db(config.MONGODB_DB);
const [users, teams, openTeams, build] = await Promise.all([
  db.collection('users').estimatedDocumentCount(),
  db.collection('teams').estimatedDocumentCount(),
  db.collection('teams').countDocuments({ isOpen: true }),
  db.admin().buildInfo(),
]);
await client.close();

const ok = cached.p95 < lt.LOADTEST_P95_TARGET_MS && cached.failed === 0;
const cpu = os.cpus();
const row = (label, f) => `| ${label} | ${f(cached)} | ${f(uncached)} |`;
const ms = (key) => (r) => `${r[key].toFixed(1)} ms`;

const report = `# Load test: board endpoint

Generated by \`npm run loadtest\` on ${new Date().toISOString()}. These are the numbers from that run, unedited.

## Result: ${ok ? 'PASS' : 'FAIL'} (target: p95 < ${lt.LOADTEST_P95_TARGET_MS} ms and 0 failed requests, default configuration)

| Metric | Default (board cache on, TTL ${config.BOARD_CACHE_TTL_MS} ms) | Cache off (every request queries MongoDB) |
| --- | --- | --- |
${row('p50 latency', ms('p50'))}
${row('p95 latency', ms('p95'))}
${row('p99 latency', ms('p99'))}
${row('max latency', ms('max'))}
${row('requests/sec (mean)', (r) => r.rps)}
${row('total requests', (r) => r.total)}
${row('2xx responses', (r) => r.ok)}
${row('errors + timeouts + non-2xx', (r) => r.failed)}

The cache-off column ${uncached.p95 < lt.LOADTEST_P95_TARGET_MS ? 'also meets' : 'does **not** meet'} the target on this machine. It is reported so the cache is not hiding anything.

## What was measured

- \`GET ${cached.board}\` rotating over three requests: first page, a page 20 cursors deep, and \`?skill=design\`.
- ${lt.LOADTEST_CONNECTIONS} concurrent connections for ${lt.LOADTEST_DURATION_SECONDS} s per pass (autocannon), page size ${config.BOARD_PAGE_SIZE_DEFAULT}.
- Data set: ${users} users, ${teams} teams (${openTeams} open), from \`npm run seed\`.
- Nothing writes during the run, so with the cache on almost every response is a cache hit. Under real traffic
  each team change clears the cache and the next reader of each page pays for one query.

## Where it was run (read this before quoting the numbers)

- One machine ran everything: load generator, API (one Node process) and MongoDB, talking over loopback.
  There is no network latency in these figures, and the load generator competes with the server for CPU.
- ${cpu[0].model.trim()}, ${cpu.length} logical cores, ${(os.totalmem() / 2 ** 30).toFixed(0)} GB RAM, ${os.type()} ${os.release()}.
- Node ${process.version}, MongoDB ${build.version} (single-node replica set).
- \`RATE_LIMIT_MAX\` was raised for the run so the per-IP limiter did not reject the load generator; nothing else differs from \`.env\`.
- A free-tier deployment (shared CPU, database in another region) will be slower. Re-run there before making claims about production.

## How the first run failed, and what fixed it

The first run of this script measured p95 = 404 ms at 349 req/s. Profiling found three causes:

1. The board handler built its zod query schema on every request. It is now built once at startup.
2. \`MONGODB_URI\` used \`localhost\`. Node tries IPv6 first and mongod was listening on IPv4 only, so each new pooled
   connection waited about 250 ms. The URI now uses \`127.0.0.1\`.
3. With those fixed the query itself takes under 1 ms (index scan, 21 keys examined), but one Node process could not
   push more than about 420 req/s of query + serialise + respond on this laptop. Board pages are now cached as
   serialized JSON, shared by concurrent readers of the same page, and cleared on every team change.
`;
writeFileSync('LOAD_TEST.md', report);
console.log(report);
process.exitCode = ok ? 0 : 1;
